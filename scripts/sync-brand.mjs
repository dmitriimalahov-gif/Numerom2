import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Checked-in outputs keep CRA, Docker and Metro builds independent of tooling.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const master = await readFile(resolve(root, 'packages/brand/numerom-logo.svg'), 'utf8');
if (/<(?:image|text|script|foreignObject)\b|(?:href|style)=|data:|url\(/i.test(master)) {
  throw new Error('Brand SVG must contain self-contained vector geometry only.');
}
const dark = master.replaceAll('#444A47', '#E8EEF8').replaceAll('#647C72', '#8BBEAA');
const square = master.replace('220 225 995 785', '220 120 995 995');
const outputs = new Map([
  ['frontend/public/images/brand/numerom-logo.svg', master],
  ['frontend/public/images/brand/numerom-logo-dark.svg', dark],
  ['frontend/public/favicon.svg', square],
  ['frontend/public/icon-192x192.svg', square],
  ['frontend/public/icon-512x512.svg', square],
  ['mobile/assets/brand/logo.generated.ts', `// Generated by scripts/sync-brand.mjs. Edit packages/brand/numerom-logo.svg.\nexport const logoLight = ${JSON.stringify(master)};\nexport const logoDark = ${JSON.stringify(dark)};\nexport const logoAspectRatio = 995 / 785;\n`],
]);
let stale = false;
for (const [relative, expected] of outputs) {
  const target = resolve(root, relative);
  if (process.argv.includes('--check')) {
    const actual = await readFile(target, 'utf8').catch(() => null);
    if (actual !== expected) { console.error(`Out of date: ${relative}`); stale = true; }
  } else {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, expected);
  }
}
if (stale) process.exitCode = 1;
else console.log(process.argv.includes('--check') ? 'Brand assets are in sync.' : 'Brand assets updated.');
